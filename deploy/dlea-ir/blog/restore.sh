#!/usr/bin/env bash
# =============================================================================
# restore.sh — bring the old Netafraz WordPress blog back up as blog.dlea.ir
#
# Run ON the VPS (37.255.212.62) as the user that owns docker (ghafari):
#   cd /home/ghafari/dlea-ir/blog && bash restore.sh
#
# Expects in ./import/  (created by the operator, not in git):
#   dlea.ir.zip                      — the hosting account archive (or parts/)
#   dleair1_uXobJspa_*.sql.gz        — the WordPress database dump
#
# What it does, idempotently:
#   1. docker network + MariaDB container (no published port)
#   2. unpacks the archive into ./html (the WordPress docroot)
#   3. writes ./html/wp-config.php from ./.env, keeping the original salts
#   4. imports the dump once (only when wp_posts is empty)
#   5. runs the WordPress container on 127.0.0.1:${WP_PORT:-8090}
#   6. rewrites www.dlea.ir -> blog.dlea.ir in the DB via wp-cli
#
# It never touches the dlea app stack (dlea-frontend / dlea-backend /
# dlea-postgres) and never binds a public port.
# =============================================================================
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"
[ -f .env ] || { echo "missing ./.env (copy .env.example)" >&2; exit 1; }
set -a; . ./.env; set +a

: "${WP_DB_NAME:?}" "${WP_DB_USER:?}" "${WP_DB_PASSWORD:?}" "${WP_DB_ROOT_PASSWORD:?}"
PORT="${WP_PORT:-8090}"
SITE_URL="${WP_SITE_URL:-https://blog.dlea.ir}"
OLD_HOSTS=("https://www.dlea.ir" "http://www.dlea.ir" "https://dlea.ir" "http://dlea.ir")
IMPORT_DIR="$PWD/import"
HTML_DIR="$PWD/html"

say() { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }

# ---------------------------------------------------------------- network ----
say "docker network"
docker network inspect dlea-blog-net >/dev/null 2>&1 || docker network create dlea-blog-net >/dev/null

# --------------------------------------------------------------------- db ----
say "MariaDB container"
if ! docker inspect dlea-blog-db >/dev/null 2>&1; then
  docker run -d --name dlea-blog-db --restart unless-stopped \
    --network dlea-blog-net \
    -e MARIADB_DATABASE="$WP_DB_NAME" -e MARIADB_USER="$WP_DB_USER" \
    -e MARIADB_PASSWORD="$WP_DB_PASSWORD" -e MARIADB_ROOT_PASSWORD="$WP_DB_ROOT_PASSWORD" \
    -v dlea-blog-db:/var/lib/mysql mariadb:11 >/dev/null
  echo "   created"
else
  docker start dlea-blog-db >/dev/null 2>&1 || true
  echo "   already exists"
fi

echo -n "   waiting for MariaDB"
for _ in $(seq 1 60); do
  if docker exec dlea-blog-db mariadb-admin ping -u root -p"$WP_DB_ROOT_PASSWORD" >/dev/null 2>&1; then
    echo " ok"; break
  fi
  echo -n "."; sleep 2
done

# ------------------------------------------------------------------- html ----
say "WordPress files"
if [ ! -f "$HTML_DIR/index.php" ]; then
  mkdir -p "$HTML_DIR"
  ZIP="$IMPORT_DIR/dlea.ir.zip"
  if [ ! -f "$ZIP" ] && ls "$IMPORT_DIR"/parts/part_* >/dev/null 2>&1; then
    echo "   reassembling the archive from parts/"
    cat $(ls -1 "$IMPORT_DIR"/parts/part_* | sort) > "$ZIP"
  fi
  [ -f "$ZIP" ] || { echo "missing $ZIP (or import/parts/)" >&2; exit 1; }
  TMP=$(mktemp -d)
  # unzip exits 1 on harmless warnings (e.g. a name with a space), which would
  # abort the whole script under `set -e` — accept the warnings, verify the core.
  unzip -q "$ZIP" 'dlea.ir/public_html/*' -d "$TMP" || echo "   unzip reported warnings, continuing"
  [ -f "$TMP/dlea.ir/public_html/index.php" ] || { echo "archive did not unpack" >&2; exit 1; }
  cp -a "$TMP/dlea.ir/public_html/." "$HTML_DIR/"
  rm -rf "$TMP"
  echo "   unpacked into $HTML_DIR"
else
  echo "   already unpacked"
fi

# --------------------------------------------------------------- wp-config ---
say "wp-config.php"
if [ -f "$HTML_DIR/wp-config.php" ] && grep -q "DLEA-BLOG-CONFIG" "$HTML_DIR/wp-config.php"; then
  echo "   already ours, leaving as-is"
else
  SALTS=""
  if [ -f "$HTML_DIR/wp-config.php" ]; then
    # Keep the original salts so existing sessions/hashes stay coherent.
    SALTS=$(sed -n "/AUTH_KEY/,/NONCE_SALT/p" "$HTML_DIR/wp-config.php" | grep -E "define\(" || true)
  fi
  if [ -z "$SALTS" ]; then
    SALTS=$(cat <<'SALTS'
define( 'AUTH_KEY',         getenv('WP_HOME') . '|a1' );
define( 'SECURE_AUTH_KEY',  getenv('WP_HOME') . '|a2' );
define( 'LOGGED_IN_KEY',    getenv('WP_HOME') . '|a3' );
define( 'NONCE_KEY',        getenv('WP_HOME') . '|a4' );
define( 'AUTH_SALT',        getenv('WP_HOME') . '|a5' );
define( 'SECURE_AUTH_SALT', getenv('WP_HOME') . '|a6' );
define( 'LOGGED_IN_SALT',   getenv('WP_HOME') . '|a7' );
define( 'NONCE_SALT',       getenv('WP_HOME') . '|a8' );
SALTS
)
  fi
  cat > "$HTML_DIR/wp-config.php" <<PHP
<?php
/** DLEA-BLOG-CONFIG — generated by deploy/dlea-ir/blog/restore.sh */

define( 'DB_NAME',     '${WP_DB_NAME}' );
define( 'DB_USER',     '${WP_DB_USER}' );
define( 'DB_PASSWORD', '${WP_DB_PASSWORD}' );
define( 'DB_HOST',     'dlea-blog-db:3306' );
define( 'DB_CHARSET',  'utf8mb4' );
define( 'DB_COLLATE',  '' );

/** Absolute URLs — WordPress must never emit the old host or the proxy origin. */
define( 'WP_HOME',    '${SITE_URL}' );
define( 'WP_SITEURL', '${SITE_URL}' );
define( 'FORCE_SSL_ADMIN', true );

/** Behind nginx; trust its X-Forwarded-Proto. */
if ( isset( \$_SERVER['HTTP_X_FORWARDED_PROTO'] ) && 'https' === \$_SERVER['HTTP_X_FORWARDED_PROTO'] ) {
    \$_SERVER['HTTPS'] = 'on';
}

$SALTS

\$table_prefix = 'wp_';

define( 'WP_DEBUG', false );
define( 'DISALLOW_FILE_EDIT', true );
define( 'WP_AUTO_UPDATE_CORE', false );

if ( ! defined( 'ABSPATH' ) ) {
    define( 'ABSPATH', __DIR__ . '/' );
}
require_once ABSPATH . 'wp-settings.php';
PHP
  echo "   written"
fi

# ------------------------------------------------------------------- data ----
say "database import"
IMPORTED=$(docker exec dlea-blog-db mariadb -N -B -u root -p"$WP_DB_ROOT_PASSWORD" \
            -e "SELECT COUNT(*) FROM information_schema.tables WHERE table_schema='$WP_DB_NAME' AND table_name='wp_posts'" 2>/dev/null || echo 0)
if [ "${IMPORTED:-0}" = "0" ]; then
  DUMP=$(ls -1 "$IMPORT_DIR"/dleair1_uXobJspa_*.sql.gz 2>/dev/null | head -1 || true)
  [ -n "$DUMP" ] || { echo "missing the .sql.gz dump in import/" >&2; exit 1; }
  echo "   importing $(basename "$DUMP")"
  gunzip -c "$DUMP" | docker exec -i dlea-blog-db mariadb -u root -p"$WP_DB_ROOT_PASSWORD" "$WP_DB_NAME"
else
  echo "   already imported"
fi

# -------------------------------------------------------------- container ----
say "WordPress container"
docker rm -f dlea-blog >/dev/null 2>&1 || true
# The docroot is a bind mount, so the container's www-data (33) must own it.
chown -R 33:33 "$HTML_DIR" 2>/dev/null || true
docker run -d --name dlea-blog --restart unless-stopped \
  --network dlea-blog-net \
  -p "127.0.0.1:${PORT}:80" \
  -e WORDPRESS_DB_HOST=dlea-blog-db -e WORDPRESS_DB_NAME="$WP_DB_NAME" \
  -e WORDPRESS_DB_USER="$WP_DB_USER" -e WORDPRESS_DB_PASSWORD="$WP_DB_PASSWORD" \
  -v "$HTML_DIR:/var/www/html" \
  wordpress:php8.3-apache >/dev/null
echo "   dlea-blog on 127.0.0.1:${PORT}"

echo -n "   waiting for http"
for _ in $(seq 1 60); do
  if curl -fsS -o /dev/null "http://127.0.0.1:${PORT}/wp-login.php" 2>/dev/null; then echo " ok"; break; fi
  echo -n "."; sleep 2
done

# ------------------------------------------------------------------ hosts ----
say "rewriting the old host to ${SITE_URL}"
docker run --rm --network dlea-blog-net \
  -v "$HTML_DIR:/var/www/html" \
  --entrypoint wp wordpress:cli-php8.3 \
  --allow-root --path=/var/www/html search-replace 'www.dlea.ir' "${SITE_URL#https://}" \
  --all-tables-with-prefix --precise --skip-columns=guid 2>/dev/null || \
  echo "   (wp-cli skipped — check the URLs in wp-admin → Settings)"

say "done — now point /etc/nginx/sites-available/blog.dlea.ir at 127.0.0.1:${PORT}"
